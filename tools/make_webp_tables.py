"""Generates src/PdfNetStack/Imaging/WebPTables.g.cs from the text of RFC 6386 and RFC 9649.

Usage: python tools/make_webp_tables.py <rfc6386.txt> <rfc9649.txt> <output .cs file>

The RFCs are at https://www.rfc-editor.org/rfc/rfc6386.txt and
https://www.rfc-editor.org/rfc/rfc9649.txt. The VP8 tables of RFC 6386 are also part of the
reference decoder it carries (section 20), under Google's BSD license; the distance map of
RFC 9649 is a code component under the Revised BSD License (see THIRD-PARTY-NOTICES.md).

From RFC 6386 the script reads the probability and dequantization tables the VP8 key frame
decoder needs; from RFC 9649 the lossless format's distance map. Each becomes a flat array.
"""

import re
import sys
from pathlib import Path

# (declaration in RFC 6386, C# name, C# element type, element count)
VP8_TABLES = [
    ("const Prob kf_bmode_prob [num_intra_bmodes] [num_intra_bmodes]", "KeyFrameSubblockModeProbabilities", "byte", 10 * 10 * 9),
    ("const Prob coeff_update_probs [4] [8] [3] [num_dct_tokens-1] =", "CoefficientUpdateProbabilities", "byte", 4 * 8 * 3 * 11),
    ("const Prob default_coeff_probs [4] [8] [3] [num_dct_tokens - 1] =", "DefaultCoefficientProbabilities", "byte", 4 * 8 * 3 * 11),
    ("static const int dc_qlookup[QINDEX_RANGE] =", "DcQuantizer", "short", 128),
    ("static const int ac_qlookup[QINDEX_RANGE] =", "AcQuantizer", "short", 128),
]

DOC = {
    "KeyFrameSubblockModeProbabilities": "VP8 subblock mode probabilities in key frames, by above mode, left mode and tree node (RFC 6386, 11.5).",
    "CoefficientUpdateProbabilities": "VP8 probabilities that a frame header updates a token probability, by plane, band, context and node (RFC 6386, 13.4).",
    "DefaultCoefficientProbabilities": "VP8 token probabilities before any update, by plane, band, context and node (RFC 6386, 13.5).",
    "DcQuantizer": "VP8 DC dequantization factors by quantizer index (RFC 6386, 14.1).",
    "AcQuantizer": "VP8 AC dequantization factors by quantizer index (RFC 6386, 14.1).",
    "DistanceMap": "WebP lossless distance codes 1 to 120 as (x, y) offsets to an earlier pixel (RFC 9649, 3.6.2.2.1).",
}

PAGE_BREAKS = [
    r"^Bankoski, et al\.\s+Informational\s+\[Page \d+\]$",
    r"^RFC 6386\s+VP8 Data Format and Decoding Guide\s+November 2011$",
    r"^Zern, et al\.\s+Informational\s+\[Page \d+\]$",
    r"^RFC 9649\s+WebP Image Format\s+November 2024$",
]


def body_lines(text):
    """The RFC without page footers, headers and form feeds."""
    for line in text.replace("\f", "\n").splitlines():
        if any(re.match(p, line) for p in PAGE_BREAKS):
            continue
        yield line


def braced(lines, declaration, count):
    """The numbers of the first listing of a table: some tables are declared before they are listed."""
    for start, line in enumerate(lines):
        if line.strip() != declaration.strip():
            continue
        rest = "\n".join(lines[start + 1:start + 6])
        if rest.find("{") >= 0 and (rest.find(";") < 0 or rest.find("{") < rest.find(";")):
            break
    else:
        raise SystemExit(f"{declaration}: not found")
    depth, values, opened = 0, [], False
    for line in lines[start + 1:]:
        for token in re.findall(r"[{}]|\d+", line):
            if token == "{":
                depth += 1
                opened = True
            elif token == "}":
                depth -= 1
            elif opened:
                values.append(int(token))
        if opened and depth == 0:
            break
    if len(values) != count:
        raise SystemExit(f"{declaration}: expected {count} values, found {len(values)}")
    return values


def distance_map(lines):
    """The (xi, yi) pairs listed before the caption of Figure 20."""
    start = next(i for i, line in enumerate(lines) if "The mapping between distance code distance_code" in line)
    end = next(i for i in range(start, len(lines)) if "Figure 20:" in lines[i])
    pairs = re.findall(r"\((-?\d+),\s*(-?\d+)\)", " ".join(lines[start:end]))
    if len(pairs) != 120:
        raise SystemExit(f"distance map: expected 120 pairs, found {len(pairs)}")
    return [int(v) for pair in pairs for v in pair]


def emit(out, name, kind, values, first):
    if not first:
        out.append("")
    out.append(f"    /// <summary>{DOC[name]}</summary>")
    out.append(f"    public static readonly {kind}[] {name} =")
    out.append("    [")
    for row in range(0, len(values), 16):
        out.append("        " + " ".join(f"{v}," for v in values[row:row + 16]))
    out.append("    ];")


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    vp8 = list(body_lines(Path(sys.argv[1]).read_text(encoding="utf-8")))
    webp = list(body_lines(Path(sys.argv[2]).read_text(encoding="utf-8")))
    out = [
        "// <auto-generated>",
        "// Generated by tools/make_webp_tables.py from RFC 6386 and RFC 9649. Do not edit.",
        "// RFC 6386 tables: Copyright (c) 2010, 2011, Google Inc. BSD license.",
        "// RFC 9649 tables: Copyright (c) 2024 IETF Trust and the persons identified as the document authors. Revised BSD License.",
        "// See THIRD-PARTY-NOTICES.md.",
        "// </auto-generated>",
        "",
        "namespace PdfNetStack.Imaging;",
        "",
        "/// <summary>Constant tables of the VP8 key frame decoder (RFC 6386) and of WebP lossless (RFC 9649).</summary>",
        "internal static class WebPTables",
        "{",
    ]
    for i, (declaration, name, kind, count) in enumerate(VP8_TABLES):
        emit(out, name, kind, braced(vp8, declaration, count), i == 0)
    emit(out, "DistanceMap", "sbyte", distance_map(webp), False)
    out.append("}")
    Path(sys.argv[3]).write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
