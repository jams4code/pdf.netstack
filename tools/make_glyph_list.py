"""Generates src/PdfNetStack/Text/Extraction/GlyphList.g.cs from the Adobe Glyph List.

Usage: python tools/make_glyph_list.py <agl-aglfn directory> <output .cs file>

The directory is a checkout of https://github.com/adobe-type-tools/agl-aglfn (BSD-3-Clause) and
holds glyphlist.txt (the AGL, glyph names to Unicode for any font) and zapfdingbats.txt (names
of the ITC Zapf Dingbats glyphs). Each list becomes one UTF-8 literal of "name hex[ hex]" lines,
which the library reads into a dictionary on first use.
"""

import re
import sys
from pathlib import Path

LINE = 100


def read(path):
    """(name, [code points]) in file order."""
    entries = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        name, values = line.split(";")
        codes = values.split()
        if not re.fullmatch(r"[A-Za-z0-9_.]+", name) or not all(re.fullmatch(r"[0-9A-F]{4}", c) for c in codes):
            raise ValueError(f"Unexpected line: {line}")
        entries.append((name, codes))
    return entries


def literal(field, entries):
    """A u8 literal of "name hex[ hex]\\n" lines, split into source lines of about LINE characters."""
    text = "".join(f"{name} {' '.join(codes)}\\n" for name, codes in entries)
    parts, current = [], ""
    for line in re.findall(r".*?\\n", text):
        if len(current) + len(line) > LINE:
            parts.append(current)
            current = ""
        current += line
    parts.append(current)
    o = [f"    internal static ReadOnlySpan<byte> {field} =>"]
    for i, p in enumerate(parts):
        o.append(f'        "{p}"u8' + (";" if i == len(parts) - 1 else " +"))
    return o


def main(source, out):
    agl = read(Path(source) / "glyphlist.txt")
    zapf = read(Path(source) / "zapfdingbats.txt")
    o = [
        "// <auto-generated>",
        "// Generated by tools/make_glyph_list.py from the Adobe Glyph List (glyphlist.txt, table version 2.0)",
        "// and zapfdingbats.txt of https://github.com/adobe-type-tools/agl-aglfn. Do not edit.",
        "// Copyright 2002-2019 Adobe. Distributed under the BSD 3-Clause license; see THIRD-PARTY-NOTICES.md.",
        "// </auto-generated>",
        "",
        "namespace PdfNetStack.Text.Extraction;",
        "",
        "internal static partial class GlyphList",
        "{",
        f"    /// <summary>The {len(agl)} AGL entries: a name, a space, then one or more UTF-16 code units in hex.</summary>",
    ]
    o += literal("AglData", agl)
    o.append("")
    o.append(f"    /// <summary>The {len(zapf)} names of the ITC Zapf Dingbats glyphs, in the same form.</summary>")
    o += literal("ZapfDingbatsData", zapf)
    o.append("}")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
