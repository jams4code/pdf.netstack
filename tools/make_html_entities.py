"""Generates src/PdfNetStack.Html/Parsing/HtmlEntities.g.cs from the WHATWG named character references.

Usage: python tools/make_html_entities.py <entities.json> <output .cs file>

entities.json comes from https://html.spec.whatwg.org/entities.json. Names are stored without the
leading ampersand; legacy names that work without the semicolon appear without it as well.
"""

import json
import sys


def main(source, out):
    entities = json.load(open(source, encoding="utf-8"))
    rows = sorted((name[1:], e["codepoints"]) for name, e in entities.items())
    o = ["// <auto-generated>",
         "// Generated by tools/make_html_entities.py from the WHATWG named character references",
         "// (https://html.spec.whatwg.org/entities.json). Do not edit.",
         "// </auto-generated>",
         "",
         "namespace PdfNetStack.Html.Parsing;",
         "",
         "internal static partial class HtmlEntities",
         "{",
         "    /// <summary>Entity names, sorted ordinally, without the ampersand.</summary>",
         "    internal static readonly string[] Names =",
         "    ["]
    for i in range(0, len(rows), 8):
        o.append("        " + ", ".join('"%s"' % r[0] for r in rows[i:i + 8]) + ",")
    o.append("    ];")
    o.append("")
    o.append("    /// <summary>Two code points per name; the second is 0 for names that stand for one character.</summary>")
    o.append("    internal static readonly int[] CodePoints =")
    o.append("    [")
    pairs = [cp for _, cps in rows for cp in (cps + [0])[:2]]
    for i in range(0, len(pairs), 16):
        o.append("        " + ", ".join("0x%X" % v for v in pairs[i:i + 16]) + ",")
    o.append("    ];")
    o.append("}")
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(o) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
