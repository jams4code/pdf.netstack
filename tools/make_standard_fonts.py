"""Generates src/PdfNetStack/Fonts/StandardFontData.g.cs from Adobe's Core14 AFM files.

Usage: python tools/make_standard_fonts.py <afm directory> <output .cs file>

The AFM files ship with matplotlib (mpl-data/fonts/pdfcorefonts) and with most PDF libraries.
Glyph names of the Latin fonts are mapped to Unicode with the Adobe Glyph List (fontTools.agl).
Symbol and ZapfDingbats are written with their built-in encodings, mapped to Unicode with
pypdf's tables of those encodings. Dev only: neither package is a dependency of the library.
"""

import os
import re
import sys

from fontTools.agl import LEGACY_AGL2UV
from pypdf._codecs import _symbol_encoding, _zapfding_encoding

LATIN = [
    "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
    "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic",
    "Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique",
]
SYMBOLIC = {"Symbol": _symbol_encoding, "ZapfDingbats": _zapfding_encoding}

# Code points that should reach a Latin glyph although the glyph list names another one. Soft
# hyphen (U+00AD) is not here: it is invisible unless a line breaks at it.
ALIASES = {
    0x00A0: "space", 0x2010: "hyphen", 0x2011: "hyphen",
    0x03BC: "mu", 0x0394: "Delta", 0x2215: "fraction",
}

NOTICE = """\
// This file and the 14 PostScript(R) AFM files it accompanies may be used, copied, and distributed
// for any purpose and without charge, with or without modification, provided that all copyright
// notices are retained; that the AFM files are not distributed without this file; that all
// modifications to this file or any of the AFM files are prominently noted in the modified
// file(s); and that this paragraph is not modified. Adobe Systems has no responsibility or
// obligation to support the use of the AFM files."""


def parse(path):
    text = open(path, encoding="latin-1").read()
    head = {}
    for line in text.split("StartCharMetrics")[0].splitlines():
        key, _, value = line.partition(" ")
        head.setdefault(key, value.strip())
    chars = []
    for m in re.finditer(r"^C (-?\d+) ; WX (\d+) ; N (\S+)", text, re.M):
        chars.append((int(m.group(1)), int(m.group(2)), m.group(3)))
    return head, chars


def num(head, key, default=0):
    return int(float(head.get(key, default)))


def ushorts(values, per_line=24):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("        " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def font_info(name, head, widths_field, extra):
    bbox = [int(v) for v in head["FontBBox"].split()]
    return (
        f'        new("{name}", "{head["FamilyName"]}", bold: {str(head["Weight"] == "Bold").lower()}, '
        f'italicAngle: {float(head["ItalicAngle"])}, fixedPitch: {head["IsFixedPitch"]}, '
        f'bbox: [{", ".join(str(v) for v in bbox)}], capHeight: {num(head, "CapHeight", bbox[3])}, '
        f'xHeight: {num(head, "XHeight", 0)}, ascender: {num(head, "Ascender", bbox[3])}, '
        f'descender: {num(head, "Descender", bbox[1])}, underlinePosition: {num(head, "UnderlinePosition")}, '
        f'underlineThickness: {num(head, "UnderlineThickness")}, stemV: {num(head, "StdVW", 80)}, '
        f"widths: {widths_field}{extra}),"
    )


def main(afm_dir, out):
    parsed = {n: parse(os.path.join(afm_dir, n + ".afm")) for n in LATIN + list(SYMBOLIC)}

    # The 12 Latin fonts share one glyph set; order it by Unicode for readable output.
    names = sorted({c[2] for c in parsed["Helvetica"][1]}, key=lambda g: (LEGACY_AGL2UV[g][0], g))
    for n in LATIN:
        assert {c[2] for c in parsed[n][1]} == set(names), n
    unicode = [LEGACY_AGL2UV[g][0] for g in names]
    index = {g: i for i, g in enumerate(names)}

    o = []
    o.append("// <auto-generated>")
    o.append("// Generated by tools/make_standard_fonts.py from the Adobe Core14 AFM files. Do not edit.")
    o.append("//")
    o.append("// MODIFIED: derived from the AFM files. Only global metrics, advance widths, glyph names and")
    o.append("// the built-in encodings of Symbol and ZapfDingbats are kept; kerning pairs, ligatures and")
    o.append("// glyph bounding boxes are removed. Copyright (c) 1985, 1987, 1989, 1990, 1991, 1992, 1993,")
    o.append("// 1997 Adobe Systems Incorporated. All Rights Reserved. The notice that accompanies the AFM files:")
    o.append("//")
    o.append(NOTICE)
    o.append("// </auto-generated>")
    o.append("")
    o.append("namespace PdfNetStack.Fonts;")
    o.append("")
    o.append("internal static class StandardFontData")
    o.append("{")
    o.append("    /// <summary>Glyph names shared by the 12 Latin fonts.</summary>")
    o.append("    internal static readonly string[] LatinNames =")
    o.append("    [")
    for i in range(0, len(names), 10):
        o.append("        " + ", ".join(f'"{g}"' for g in names[i:i + 10]) + ",")
    o.append("    ];")
    o.append("")
    o.append("    /// <summary>Unicode code point of each name in <see cref=\"LatinNames\"/>.</summary>")
    o.append("    internal static readonly int[] LatinUnicode =")
    o.append("    [")
    o.append(ushorts(unicode, 16))
    o.append("    ];")
    o.append("")
    o.append("    /// <summary>Other code points drawn with a Latin glyph: pairs of code point and glyph index.</summary>")
    o.append("    internal static readonly int[] LatinAliases =")
    o.append("    [")
    o.append("        " + ", ".join(f"0x{cp:04X}, {index[g]}" for cp, g in sorted(ALIASES.items())) + ",")
    o.append("    ];")

    widths_fields = {}
    for n in LATIN:
        w = {c[2]: c[1] for c in parsed[n][1]}
        widths = tuple(w[g] for g in names)
        if widths not in widths_fields:
            widths_fields[widths] = n.replace("-", "") + "Widths"

    for widths, field in widths_fields.items():
        o.append("")
        o.append(f"    private static readonly ushort[] {field} =")
        o.append("    [")
        o.append(ushorts(widths))
        o.append("    ];")

    for n, encoding in SYMBOLIC.items():
        chars = [c for c in parsed[n][1] if c[0] >= 0]
        o.append("")
        o.append(f"    private static readonly byte[] {n}Codes =")
        o.append("    [")
        o.append(ushorts([c[0] for c in chars]))
        o.append("    ];")
        o.append("")
        o.append(f"    private static readonly int[] {n}Unicode =")
        o.append("    [")
        o.append(ushorts([ord(encoding[c[0]]) for c in chars], 16))
        o.append("    ];")
        o.append("")
        o.append(f"    private static readonly ushort[] {n}Widths =")
        o.append("    [")
        o.append(ushorts([c[1] for c in chars]))
        o.append("    ];")

    o.append("")
    o.append("    internal static readonly StandardFontInfo[] Fonts =")
    o.append("    [")
    for n in LATIN:
        w = {c[2]: c[1] for c in parsed[n][1]}
        field = widths_fields[tuple(w[g] for g in names)]
        o.append(font_info(n, parsed[n][0], field, ""))
    for n in SYMBOLIC:
        o.append(font_info(n, parsed[n][0], f"{n}Widths", f", codes: {n}Codes, unicode: {n}Unicode"))
    o.append("    ];")
    o.append("}")

    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
